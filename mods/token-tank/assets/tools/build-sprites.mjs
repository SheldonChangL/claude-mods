#!/usr/bin/env node
// Compiles sprites into render/sprites.ts: every frame becomes one SVG path
// per colour (horizontal 1 px runs), so a sprite is a few hundred bytes.
// Input: a folder of one JSON per sprite ({ name, w, h, palette, frames }),
// or a sprites.json ({ sprites: {...} }). A sprite missing from the folder,
// or one with a bad frame, falls back to sprites.placeholder.json.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = process.argv[2] ?? join(here, '..', 'sprites')
const out = process.argv[3] ?? join(here, '..', '..', 'render', 'sprites.ts')
const placeholder = JSON.parse(readFileSync(join(here, '..', 'sprites.placeholder.json'), 'utf8')).sprites

/** One sprite → { w, h, frames: { anim: [ [ {fill, d} ] ] } }, or the problems found. */
function compileOne(name, sprite) {
  const { w, h, palette, frames } = sprite
  const problems = []
  const anims = {}
  for (const [anim, list] of Object.entries(frames)) {
    anims[anim] = list.map((rows, fi) => {
      if (rows.length !== h) problems.push(`${name}.${anim}[${fi}]: ${rows.length} rows, want ${h}`)
      const byColor = new Map()
      rows.forEach((row, y) => {
        if (row.length !== w) problems.push(`${name}.${anim}[${fi}] row ${y}: ${row.length} chars, want ${w}`)
        let x = 0
        while (x < row.length) {
          const c = row[x]
          if (c === '.') { x++; continue }
          let n = 1
          while (row[x + n] === c) n++
          if (!palette[c]) problems.push(`${name}.${anim}[${fi}] row ${y}: '${c}' not in palette`)
          const d = byColor.get(c) ?? []
          d.push(`M${x} ${y}h${n}v1h-${n}z`)
          byColor.set(c, d)
          x += n
        }
      })
      return [...byColor].map(([c, d]) => ({ fill: palette[c], d: d.join('') }))
    })
  }
  return { sprite: { w, h, frames: anims }, problems }
}

let sources
if (statSync(src).isDirectory()) {
  sources = {}
  for (const f of readdirSync(src).filter(f => f.endsWith('.json')).sort()) {
    const one = JSON.parse(readFileSync(join(src, f), 'utf8'))
    sources[one.name ?? f.replace(/\.json$/, '')] = one
  }
} else {
  sources = JSON.parse(readFileSync(src, 'utf8')).sprites
}

const compiled = {}
const report = []
for (const name of Object.keys(placeholder)) {
  const real = sources[name]
  if (real) {
    const { sprite, problems } = compileOne(name, real)
    if (problems.length === 0) { compiled[name] = sprite; report.push(`${name}: art`); continue }
    console.error(problems.join('\n'))
  }
  compiled[name] = compileOne(name, placeholder[name]).sprite
  report.push(`${name}: placeholder`)
}
for (const name of Object.keys(sources)) if (!placeholder[name]) {
  const { sprite, problems } = compileOne(name, sources[name])
  if (problems.length === 0) { compiled[name] = sprite; report.push(`${name}: art (extra)`) } else console.error(problems.join('\n'))
}
const body = `// Generated by assets/tools/build-sprites.mjs. Do not edit.
export type SpritePath = { fill: string; d: string }
export type SpriteFrame = SpritePath[]
export type Sprite = { w: number; h: number; frames: Record<string, SpriteFrame[]> }
export const SPRITES: Record<string, Sprite> = ${JSON.stringify(compiled)}
`
writeFileSync(out, body)
console.log(report.join(', '))
console.log(`wrote ${out}: ${Object.keys(compiled).length} sprites, ${body.length} chars`)
